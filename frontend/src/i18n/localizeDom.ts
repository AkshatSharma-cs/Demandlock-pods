const english = Object.fromEntries(Object.entries(hindi).map(([key, value]) => [value, key]));

function translateAttributes(element: Element, dictionary: Record<string, string>) {
  for (const name of ["placeholder", "aria-label", "title"]) {
    const value = element.getAttribute(name);
    if (value && dictionary[value]) element.setAttribute(name, dictionary[value]);
  }
}

export function localizeDom(root: HTMLElement, language: string) {
  const dictionary = language === "hi" ? hindi : language === "en" ? english : {};
  if (!Object.keys(dictionary).length) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  let node: Node | null;
  while ((node = walker.nextNode())) nodes.push(node as Text);
  nodes.forEach(text => {
    const value = text.nodeValue || "";
    if (dictionary[value]) text.nodeValue = dictionary[value];
  });
  root.querySelectorAll("*").forEach(element => translateAttributes(element, dictionary));
}
